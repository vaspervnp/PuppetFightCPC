#!/usr/bin/env python3
"""Convert the sprite PNGs into Amstrad CPC Mode 0 data.

Input:  art/sprites/<char>.json and art/sprites/<char>/<move>_<n>.png
Output: data/sprites/<char>.asm   frame table + masked sprite data (db lines)
        data/sprites/<char>.bin   the same frame data, raw, for disk loading
        data/sprites/palette.asm  Gate Array ink numbers for pens 0-15

Mode 0 packs two pixels per byte. Pen bits 0,1,2,3 of the left pixel go to
byte bits 7,3,5,1; the right pixel uses bits 6,2,4,0.

Each frame is stored as:
    db width_bytes, height, offset_x_bytes (signed)
    then height lines of width_bytes (mask, data) pairs
Draw with: screen = (screen AND mask) OR data. Pen 0 is transparent
(mask bits 1); pen 15 is the opaque black outline.

These are the masked source frames; the compiled-sprite generator for the
engine will read the same PNGs and emit LD/AND/OR code per frame.
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cpc_palette import GAME_PALETTE, HW_COLOURS, TRANSPARENT  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LEFT_BITS = (7, 3, 5, 1)
RIGHT_BITS = (6, 2, 4, 0)


def encode_pixel(pen, bits):
    return sum(((pen >> i) & 1) << b for i, b in enumerate(bits))


def encode_byte(left, right):
    data = encode_pixel(left, LEFT_BITS) | encode_pixel(right, RIGHT_BITS)
    mask = 0
    if left == TRANSPARENT:
        mask |= encode_pixel(15, LEFT_BITS)
    if right == TRANSPARENT:
        mask |= encode_pixel(15, RIGHT_BITS)
    return mask, data


def encode_frame(im):
    px = im.load()
    w, h = im.size
    lines = []
    for y in range(h):
        lines.append([encode_byte(px[x, y], px[x + 1, y]) for x in range(0, w, 2)])
    return lines


def frame_stats(lines):
    opaque = sum(1 for ln in lines for m, _ in ln if m == 0)
    partial = sum(1 for ln in lines for m, _ in ln if m not in (0, 0xFF))
    return opaque, partial


def export(char):
    with open(os.path.join(REPO, "art", "sprites", char + ".json")) as f:
        tbl = json.load(f)
    out_dir = os.path.join(REPO, "data", "sprites")
    os.makedirs(out_dir, exist_ok=True)

    label = char.upper()
    asm = ["; %s sprite frames - generated by tools/cpc_export.py, do not edit" % char,
           "; frame: db width_bytes, height, offset_x_bytes, then (mask,data) pairs",
           ""]
    blob = bytearray()
    frames = []
    for move in tbl["moves"]:
        for fr in move["frames"]:
            im = Image.open(os.path.join(REPO, "art", "sprites", char, fr["file"] + ".png"))
            assert im.mode == "P", fr["file"]
            lines = encode_frame(im)
            wb = im.width // 2
            off = fr["offset_x"] // 2
            name = "%s_%s" % (label, fr["file"].upper())
            frames.append((move["name"], name, len(blob)))
            head = bytes([wb, im.height, off & 0xFF])
            blob += head
            asm.append("%s:  ; %dx%d px, %s" % (name, im.width, im.height,
                                                "opaque %d / partial %d bytes" % frame_stats(lines)))
            asm.append("    db %d,%d,%d" % (wb, im.height, off))
            for ln in lines:
                flat = [b for pair in ln for b in pair]
                blob += bytes(flat)
                asm.append("    db " + ",".join("#%02X" % b for b in flat))
            asm.append("")

    # move table: per move, frame count + pointers
    table = ["%s_MOVES:" % label]
    for move in tbl["moves"]:
        table.append("    dw %s_MOVE_%s" % (label, move["name"].upper()))
    table.append("")
    for move in tbl["moves"]:
        names = [n for m, n, _ in frames if m == move["name"]]
        table.append("%s_MOVE_%s:" % (label, move["name"].upper()))
        table.append("    db %d" % len(names))
        table.append("    dw " + ",".join(names))
    table.append("")
    move_ids = ["%s_%s equ %d" % ("MOVE", m["name"].upper(), i) for i, m in enumerate(tbl["moves"])]

    with open(os.path.join(out_dir, char + ".asm"), "w") as f:
        f.write("\n".join(asm[:3] + move_ids + [""] + table + asm[3:]))
    with open(os.path.join(out_dir, char + ".bin"), "wb") as f:
        f.write(blob)
    return len(frames), len(blob)


def export_palette():
    lines = ["; game palette - generated by tools/cpc_export.py",
             "; pen n -> Gate Array colour byte (select pen with OUT &7F,pen then OUT &7F,value)",
             "PALETTE:"]
    inks = [HW_COLOURS[c][2] for c in GAME_PALETTE]
    names = [HW_COLOURS[c][0] for c in GAME_PALETTE]
    for pen, (ink, name) in enumerate(zip(inks, names)):
        lines.append("    db #%02X  ; pen %2d %s" % (ink, pen, name))
    with open(os.path.join(REPO, "data", "sprites", "palette.asm"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    export_palette()
    for c in sys.argv[1:] or ["trump", "putin"]:
        n, size = export(c)
        print("%s: %d frames, %d bytes (%.1f KB) masked data" % (c, n, size, size / 1024))
