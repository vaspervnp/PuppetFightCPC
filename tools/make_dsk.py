#!/usr/bin/env python3
"""The game's disc: an EXTENDED CPC DSK image in AMSDOS's data format, and
the map of where the engine finds its files on it.

    tools/make_dsk.py map             src/gen/diskmap.asm
    tools/make_dsk.py write OUT.dsk   the image

The format: one side, 42 tracks, every one formatted (tracks 40-41 too,
which AMSDOS never uses but some drives and emulators refuse to read if
they aren't there), 9 sectors of 512 bytes, IDs #C1-#C9 in AMSDOS's 2:1
interleave (C1 C6 C2 C7 C3 C8 C4 C9 C5). Logical sector s is track s / 9,
sector #C1 + s mod 9; 1K blocks from track 0, the directory in blocks 0-1.

The files go on in a fixed order, each from a fresh block: first the ones
the engine reads mid-game with its own disc reading (src/disc.asm), the
character files (in the roster's order) and the stages, so that where they
are depends only on them and not on the engine, which comes last. Every
file is in the directory, so the loader can read them all through the
firmware as well.

The map gives the engine, for each character of the roster, the track and
sector its file starts at (the AMSDOS header, then the file) and the same
for its home stage.
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(REPO, "build")
TRACKS = 42
AMSDOS_TRACKS = 40
SECTORS = 9
SECTOR = 512
BLOCK = 1024
DIR_BLOCKS = 2
DIR_ENTRIES = 64
INTERLEAVE = [0xC1, 0xC6, 0xC2, 0xC7, 0xC3, 0xC8, 0xC4, 0xC9, 0xC5]
GAP3 = 0x52                     # the format's gap (the firmware's)
FILLER = 0xE5


def roster():
    """The characters, from the Makefile's CHARS (via the environment)."""
    return os.environ.get("CHARS", "trump putin kim xi musk zelensky").split()


def home_stage(char):
    with open(os.path.join(REPO, "art", "sprites", char + "_pfc.json")) as fh:
        stage = json.load(fh)["stage"]
    with open(os.path.join(REPO, "art", "stages", stage + ".json")) as fh:
        return json.load(fh)["name"]


def stages():
    out = []
    for c in roster():
        s = home_stage(c)
        if s not in out:
            out.append(s)
    return out


def files():
    """(disc name, path, kind, load, exec) in the order they go on the
    disc. kind: 'bin' (an AMSDOS header) or 'txt' (none)."""
    out = [(c.upper() + ".PFC", os.path.join(BUILD, "pfc", c.upper() + ".PFC"), "bin", 0x4000, 0)
           for c in roster()]
    out += [(s + ".STG", os.path.join(BUILD, "stages", s + ".STG"), "bin", 0x2000, 0)
            for s in stages()]
    out += [("ROSTER.TXT", os.path.join(BUILD, "pfc", "ROSTER.TXT"), "txt", 0, 0),
            ("TITLE.SCR", os.path.join(BUILD, "TITLE.SCR"), "bin", 0x9800, 0),
            ("PFLOAD.BIN", os.path.join(BUILD, "PFLOAD.BIN"), "bin", 0x8000, 0x8000),
            ("PFSPIKE.BAS", os.path.join(REPO, "src", "pfspike.bas"), "txt", 0, 0),
            ("PFSPIKE.BIN", os.path.join(BUILD, "PFSPIKE.BIN"), "bin", 0x4000, 0x4000)]
    return out


def amsdos_name(name):
    base, _, ext = name.partition(".")
    return base.ljust(8)[:8].encode() + ext.ljust(3)[:3].encode()


def contents(name, path, kind, load, exe):
    data = open(path, "rb").read()
    if kind == "txt":
        data = data.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
        return data + b"\x1a" * (-len(data) % 128 or 128)
    h = bytearray(128)
    h[1:12] = amsdos_name(name)
    h[0x12] = 2                                 # binary
    h[0x15:0x17] = load.to_bytes(2, "little")
    h[0x18:0x1A] = len(data).to_bytes(2, "little")
    h[0x1A:0x1C] = exe.to_bytes(2, "little")
    h[0x40:0x43] = len(data).to_bytes(3, "little")
    h[0x43:0x45] = (sum(h[:0x43]) & 0xFFFF).to_bytes(2, "little")
    return bytes(h) + data


def layout(only=None):
    """[(name, first block, contents)] for the files (the first `only` of
    them: their places don't depend on the rest)."""
    out, block = [], DIR_BLOCKS
    for f in files()[:only]:
        data = contents(*f)
        out.append((f[0], block, data))
        block += -(-len(data) // BLOCK)
    limit = AMSDOS_TRACKS * SECTORS * SECTOR // BLOCK
    if block > limit:
        sys.exit("the files need %d blocks of the disc's %d" % (block, limit))
    return out


def place(block):
    s = block * BLOCK // SECTOR
    return s // SECTORS, 0xC1 + s % SECTORS


def cmd_map():
    chars, sts = roster(), stages()
    lay = {name: block for name, block, _ in layout(len(chars) + len(sts))}
    out = [";; generated by tools/make_dsk.py map - do not edit",
           ";; Per character of the roster: the track and sector its file starts",
           ";; at, then its home stage's (src/disc.asm).",
           "DM_CHARS        EQU %d" % len(chars),
           "dm_files"]
    for c in chars:
        t, s = place(lay[c.upper() + ".PFC"])
        st, ss = place(lay[home_stage(c) + ".STG"])
        out.append("    defb %d,#%02X,%d,#%02X          ; %s" % (t, s, st, ss, c))
    text = "\n".join(out) + "\n"
    path = os.path.join(REPO, "src", "gen", "diskmap.asm")
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)


def cmd_write(out_path):
    lay = layout()
    disc = bytearray(TRACKS * SECTORS * SECTOR)
    directory = bytearray([FILLER]) * (DIR_BLOCKS * BLOCK)
    entry = 0
    for name, block, data in lay:
        disc[block * BLOCK:block * BLOCK + len(data)] = data
        records = -(-len(data) // 128)
        blocks = list(range(block, block + -(-len(data) // BLOCK)))
        for ext in range(0, len(blocks), 16):
            if entry == DIR_ENTRIES:
                sys.exit("the directory is full")
            e = bytearray(32)
            e[1:12] = amsdos_name(name)
            e[12] = ext // 16
            e[15] = min(128, records - ext * 8)
            for i, b in enumerate(blocks[ext:ext + 16]):
                e[16 + i] = b
            directory[entry * 32:entry * 32 + 32] = e
            entry += 1
    disc[:len(directory)] = directory

    track_size = 256 + SECTORS * SECTOR
    img = bytearray(256)
    img[:34] = b"EXTENDED CPC DSK File\r\nDisk-Info\r\n"
    img[0x22:0x30] = b"PuppetFightCPC"
    img[0x30] = TRACKS
    img[0x31] = 1
    for t in range(TRACKS):
        img[0x34 + t] = track_size // 256
    for t in range(TRACKS):
        ti = bytearray(256)
        ti[:12] = b"Track-Info\r\n"
        ti[0x10] = t
        ti[0x11] = 0
        ti[0x14] = 2                            # 512 bytes
        ti[0x15] = SECTORS
        ti[0x16] = GAP3
        ti[0x17] = FILLER
        body = bytearray()
        for i, r in enumerate(INTERLEAVE):
            ti[0x18 + i * 8:0x18 + i * 8 + 8] = bytes([t, 0, r, 2, 0, 0]) + SECTOR.to_bytes(2, "little")
            s = t * SECTORS + r - 0xC1
            body += disc[s * SECTOR:(s + 1) * SECTOR]
        img += ti + body
    with open(out_path, "wb") as fh:
        fh.write(img)
    used = lay[-1][1] + -(-len(lay[-1][2]) // BLOCK)
    print("%s: %d files, %d of %d blocks" % (out_path, len(lay), used,
                                             AMSDOS_TRACKS * SECTORS * SECTOR // BLOCK))


if __name__ == "__main__":
    if sys.argv[1:2] == ["map"]:
        cmd_map()
    elif sys.argv[1:2] == ["write"] and len(sys.argv) == 3:
        cmd_write(sys.argv[2])
    else:
        sys.exit(__doc__)
